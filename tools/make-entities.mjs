// Regenerates core/html-entities.mjs from the WHATWG list. Usage: node tools/make-entities.mjs <entities.json>
// (download https://html.spec.whatwg.org/entities.json first; the build never fetches it).
import { readFileSync, writeFileSync } from 'node:fs';
const entities = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const semi = [], legacy = [];
for (const [key, value] of Object.entries(entities)) {
  const name = key.slice(1).replace(/;$/, ''), cps = value.codepoints.map((c) => c.toString(36)).join('.');
  (key.endsWith(';') ? semi : legacy).push(name + '=' + cps);
}
writeFileSync(new URL('../core/html-entities.mjs', import.meta.url),
  '// HTML named character references from the WHATWG standard (https://html.spec.whatwg.org/entities.json),\n' +
  '// compacted: name=codepoints in base 36, dot-separated. LEGACY lists the names also valid without a\n' +
  '// trailing semicolon. Generated by tools/make-entities.mjs; do not edit by hand.\n' +
  'const unpack = (s) => new Map(s.split(" ").map((e) => { const i = e.indexOf("="); return [e.slice(0, i), String.fromCodePoint(...e.slice(i + 1).split(".").map((c) => parseInt(c, 36)))]; }));\n' +
  "export const ENTITIES = unpack('" + semi.join(' ') + "');\n" +
  "export const LEGACY = new Set('" + legacy.map((x) => x.split('=')[0]).join(' ') + "'.split(\" \"));\n");
