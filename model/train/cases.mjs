// Turn a held-out set of your own labeled emails into the case format evaluation/heldout/run.mjs
// scores, with the README composition table the runner checks.
//
//   node model/train/cases.mjs <held-out emails.jsonl> <out dir>
//   node evaluation/heldout/run.mjs --cases <out dir>/cases.jsonl
//
// Input lines use the training format ({id, subject, body, flags}), plus optional "from" and "to",
// each an address or {name, address}. By default a sender at company.example writes to a role
// mailbox ("Client services") at outside.example, which the greeting check ignores; give real names
// to test it. An email with flags is expected to stop; one without is expected to pass. ids.json maps
// the generated case ids back to yours.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { emailOf, readJsonl } from './mail.mjs';

const [input, out] = process.argv.slice(2);
if (!input || !out) throw new Error('Usage: node model/train/cases.mjs <held-out emails.jsonl> <out dir>');
const CATEGORY = { access: 'secrets', personal: 'personal', economics: 'economics', negotiation: 'negotiation', remark: 'remark' };
const SECTION = { secrets: '5.1', personal: '5.4', economics: '5.5', negotiation: '5.6', remark: '5.7', none: '5' };
const ALL = ['secrets', 'payment', 'government_id', 'personal', 'economics', 'negotiation', 'remark', 'lookalike', 'exposed_list', 'file', 'none'];
const counters = {}, ids = {}, cases = [];
for (const row of await readJsonl(input)) {
  const email = emailOf(row), flags = row.flags ?? [];
  const category = flags.length ? CATEGORY[flags[0].label] : 'none';
  if (!category) throw new Error(`${email.id}: unknown label ${flags[0].label}`);
  counters[category] = (counters[category] || 0) + 1;
  if (counters[category] > 999) throw new Error(`More than 999 ${category} cases: split the set`);
  const id = `${category}-${String(counters[category]).padStart(3, '0')}`;
  ids[id] = email.id;
  const address = (value, name, fallback) => typeof value === 'object' && value
    ? { name: String(value.name ?? ''), address: String(value.address), kind: 'person' }
    : { name: value ? value.split('@')[0] : name, address: value || fallback, kind: 'person' };
  cases.push({ id, category_expected: category, expect: flags.length ? 'stop' : 'pass',
    why: `SPEC §${SECTION[category]}: ${flags.length ? 'labeled ' + flags.map(f => f.label).join(', ') : 'ordinary outside mail'} (${email.id}).`,
    draft: { from: address(row.from, 'Sender', 'sender@company.example'), to: [address(row.to, 'Client services', 'clients@outside.example')], cc: [], bcc: [],
      subject: email.subject, body: { format: 'text', text: email.body }, attachments: [] } });
}
const table = ALL.map(c => {
  const stop = cases.filter(x => x.category_expected === c && x.expect === 'stop').length, pass = cases.filter(x => x.category_expected === c && x.expect === 'pass').length;
  return `| ${c} | ${stop} | 0 | ${pass} | ${stop + pass} |`;
});
const stops = cases.filter(x => x.expect === 'stop').length;
await mkdir(out, { recursive: true });
await writeFile(path.join(out, 'cases.jsonl'), cases.map(c => JSON.stringify(c)).join('\n') + '\n');
await writeFile(path.join(out, 'ids.json'), JSON.stringify(ids, null, 2) + '\n');
await writeFile(path.join(out, 'README.md'), `# Held-out cases\n\nGenerated by model/train/cases.mjs from ${path.basename(input)}. Never tune on this set.\n\n` +
  '| category_expected | stop | prompt | pass | Total |\n| --- | ---: | ---: | ---: | ---: |\n' + table.join('\n') +
  `\n| **Total** | **${stops}** | **0** | **${cases.length - stops}** | **${cases.length}** |\n`);
console.log(`${cases.length} cases (${stops} expected to stop) in ${out}`);
